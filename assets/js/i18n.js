const originalText = new WeakMap();
const originalAttributes = new WeakMap();
let currentLanguage = "it";

function translateTextNodes(language) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const parent = node.parentElement;
    if (parent && !["SCRIPT", "STYLE", "IFRAME"].includes(parent.tagName)) {
      if (!originalText.has(node)) originalText.set(node, node.nodeValue);
      const source = originalText.get(node);
      const phrase = source.trim();
      const replacement = language === "en" ? textTranslations[phrase] : phrase;
      if (replacement) node.nodeValue = source.replace(phrase, replacement);
    }
    node = walker.nextNode();
  }
}

function translateAttributes(language) {
  document.querySelectorAll("[aria-label], img[alt]").forEach((element) => {
    const attribute = element.hasAttribute("aria-label") ? "aria-label" : "alt";
    if (!originalAttributes.has(element)) {
      originalAttributes.set(element, { attribute, value: element.getAttribute(attribute) });
    }
    const original = originalAttributes.get(element);
    element.setAttribute(attribute, language === "en"
      ? (attributeTranslations[original.value] || original.value)
      : original.value);
  });
}

function setLanguage(language, persist = true) {
  currentLanguage = language === "en" ? "en" : "it";
  document.documentElement.lang = currentLanguage;
  translateTextNodes(currentLanguage);
  translateAttributes(currentLanguage);
  const page = document.body.dataset.page || "home";
  const titles = {
    home: {
      it: "TapeSense | Il tuo trading, finalmente leggibile",
      en: "TapeSense | Your trading, finally readable",
    },
    privacy: { it: "Privacy | TapeSense", en: "Privacy | TapeSense" },
    versions: { it: "Versioni | TapeSense", en: "Versions | TapeSense" },
    notFound: {
      it: "Pagina non trovata | TapeSense",
      en: "Page not found | TapeSense",
    },
  };
  document.title = titles[page]?.[currentLanguage] || titles.home[currentLanguage];
  const description = document.querySelector('meta[name="description"]');
  if (description) {
    if (page === "privacy") {
      description.content = currentLanguage === "en"
        ? "Privacy information for the TapeSense website."
        : "Informativa privacy del sito informativo TapeSense.";
    } else if (page === "versions") {
      description.content = currentLanguage === "en"
        ? "TapeSense version archive. Only the latest Windows release is available for installation."
        : "Archivio delle versioni TapeSense. Solo l’ultima release Windows è disponibile per l’installazione.";
    } else if (page === "home") {
      description.content = currentLanguage === "en"
        ? "TapeSense turns your trading journal into a clear view of execution, risk and growth. Local data, visual reports and market context."
        : "TapeSense trasforma il diario di trading in una lettura chiara di esecuzione, rischio e crescita. Dati locali, report visuali e contesto di mercato.";
    }
  }
  document.querySelectorAll("[data-language]").forEach((button) => {
    const active = button.dataset.language === currentLanguage;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  if (persist) {
    try { localStorage.setItem("tapesense-language", currentLanguage); } catch (_) { /* Storage can be unavailable. */ }
  }
  window.dispatchEvent(new CustomEvent("tapesense:languagechange", { detail: { language: currentLanguage } }));
}

export function getLanguage() {
  return currentLanguage;
}

export function initLanguageSwitcher() {
  let initial = "it";
  try { initial = localStorage.getItem("tapesense-language") === "en" ? "en" : "it"; } catch (_) { /* Default to Italian. */ }
  document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
  });
  setLanguage(initial, false);
}
